# La marca: lupa blanca sobre tinta, con el punto de marca arriba a la derecha.
_APP_ICON = (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128">'
    '<rect x="4" y="4" width="120" height="120" rx="30" fill="{background}"/>'
    '<g fill="none" stroke="#ffffff" stroke-width="11" stroke-linecap="round">'
    '<circle cx="58" cy="60" r="24"/><path d="m76 78 16 16"/></g>'
    '<circle cx="100" cy="28" r="12" fill="#ee5b2b"/></svg>'
)


def _render(svg: str, size: int) -> QPixmap:
    renderer = QSvgRenderer(QByteArray(svg.encode()))
    pixmap = QPixmap(size * PIXEL_RATIO, size * PIXEL_RATIO)
    pixmap.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()
    pixmap.setDevicePixelRatio(PIXEL_RATIO)
    return pixmap


def line_pixmap(name: str, color: str, size: int = 18, stroke: float = 2.0) -> QPixmap:
    body = _LINE_ICONS[name].replace("{color}", color)
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
           f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')
    return _render(svg, size)


def line_icon(name: str, color: str, size: int = 18) -> QIcon:
    return QIcon(line_pixmap(name, color, size))


def app_pixmap(size: int, background: str = "#1a1917") -> QPixmap:
    return _render(_APP_ICON.replace("{background}", background), size)


def app_icon() -> QIcon:
    icon = QIcon()
    for size in (16, 24, 32, 48, 64, 128):
        icon.addPixmap(app_pixmap(size))
    return icon
